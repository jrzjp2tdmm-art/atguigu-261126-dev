"""
    float()函数 将指定的数据转换为float类型
"""

print(float("3.5"))
print(float(100))
print(float(3.5))
print(float("nan")) # not a number 不是一个数值  nan属于一种特殊的数据标识
print(float("NaN")) # not a number 不是一个数值  NaN属于一种特殊的数据标识
print(float("inf")) #  无穷
print(float("-inf")) #  负无穷
print(float("infinity"))#  无穷
print(float("-infinity"))#  负无穷
# print(float("abc"))# ValueError: could not convert string to float: 'abc'

print(float(2E3))


